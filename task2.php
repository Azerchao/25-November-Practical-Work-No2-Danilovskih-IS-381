<?php
// Задача 2. Захват переменных
$discount = 0.9;
$applyDiscount = fn($price) => $price * $discount; // $discount захвачена автоматически

foreach ([100, 250, 1000] as $p) {
    echo "Цена $p -> ", $applyDiscount($p), "\n"; // 90, 225, 900
}

$discount = 0.5; // меняем ПОСЛЕ создания функции
echo "После изменения: ", $applyDiscount(100), "\n"; // всё равно 90

// Почему не изменилось: fn захватывает внешние переменные ПО ЗНАЧЕНИЮ
// и в МОМЕНТ СОЗДАНИЯ функции. Внутри хранится копия 0.9,
// и последующее изменение $discount на неё не влияет.

$rate = 92.5; // курс валюты
$toRubles = fn($usd) => $usd * $rate * $discount; // две внешние переменные сразу
echo $toRubles(10), "\n"; // 10 * 92.5 * 0.5 = 462.5
